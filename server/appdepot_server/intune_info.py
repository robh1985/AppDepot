"""Text documents that accompany each .intunewin package."""

from __future__ import annotations

import datetime as dt

from .installers import DEFAULT_RETURN_CODES, INSTALLER_TYPES, MSI_TYPES


def deployment_text(*, app: dict, version: dict) -> str:
    """Human-readable Intune deployment sheet.

    ``app`` and ``version`` are plain dicts (see Updater._intune_context).
    """
    itype = version["installer_type"]
    scope = (version.get("scope") or app.get("scope") or "machine").lower()
    behavior = "System" if scope != "user" else "User"
    lines = [
        "=" * 78,
        f" Intune Win32 app deployment - {app['name']} {version['version']}",
        "=" * 78,
        "",
        "APP INFORMATION",
        f"  Name ............... {app['name']}",
        f"  Version ............ {version['version']}",
        f"  Publisher .......... {app.get('publisher') or ''}",
        f"  Description ........ {(app.get('description') or '').strip()}",
        f"  Information URL .... {app.get('homepage') or ''}",
        f"  Category ........... {app.get('category') or ''}",
        "",
        "PACKAGE",
        f"  Package file ....... {version['intunewin_name']}",
        f"  Setup file ......... {version['filename']}" + (f"  (from {version['archive']})" if version.get("archive") else ""),
        f"  Installer type ..... {INSTALLER_TYPES.get(itype, {}).get('label', itype)}",
        f"  Architecture ....... {version.get('architecture') or 'any'}",
        f"  SHA-256 ............ {version['sha256']}",
        f"  Source URL ......... {version.get('source_url') or ''}",
        f"  Downloaded ......... {version['downloaded_at']:%Y-%m-%d %H:%M} UTC",
        "",
        "PROGRAM",
        "  Install command:",
        f"    {version['install_command']}",
        "",
        "  Uninstall command:",
        f"    {version.get('uninstall_command') or _no_uninstall(itype)}",
        "",
        f"  Install behavior ... {behavior}",
        "  Device restart ..... Determine behavior based on return codes",
        "",
        "  Return codes:",
    ]
    lines += [f"    {code:<6} {meaning}" for code, meaning in DEFAULT_RETURN_CODES]
    if version.get("target_product_codes"):
        lines += ["", "  This patch applies to these installed products (ProductCode):"]
        lines += [f"    {code}" for code in version["target_product_codes"]]
        lines += ["  Add a requirement rule so the patch only targets devices that have the product."]
    if version.get("requires"):
        lines += ["", "  DEPENDENCIES - add these AppDepot applications as Intune app dependencies",
                  "  (Dependencies tab, 'Automatically install'):"]
        lines += [f"    {dep}" for dep in version["requires"]]
    lines += ["", "REQUIREMENTS",
              f"  Operating system architecture ... {_arch_requirement(version.get('architecture'))}",
              "  Minimum operating system ........ Windows 10 1809", "",
              "DETECTION RULES (choose one)"]
    if itype in MSI_TYPES and version.get("product_code"):
        lines += [
            "  Option A - MSI:",
            f"    MSI product code ...... {version['product_code']}",
            "    Product version check . Yes",
            "    Operator .............. Greater than or equal to",
            f"    Value ................. {version.get('msi_product_version') or version['version']}",
            "",
        ]
    lines += [
        "  Option B - Custom detection script:",
        f"    Upload {version['detection_script_name']}",
        "    Run script as 32-bit process on 64-bit clients: No",
        "    Enforce script signature check: No",
        "",
        "  Option C - Registry (manual):",
        "    Key path: HKLM\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\<application key>",
        "    Value name: DisplayVersion   Detection method: Version comparison",
        f"    Operator: Greater than or equal to   Value: {version['version']}",
        "",
        "-" * 78,
        f"Generated by AppDepot on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC",
        "",
    ]
    return "\r\n".join(lines)


def _no_uninstall(itype: str) -> str:
    if itype == "msp":
        return ("cmd.exe /c exit 0    (a patch cannot be removed on its own; uninstall the product "
                "to remove it - Intune requires a command, this one does nothing)")
    return "<not available - specify installer.uninstall_command in the manifest>"


def _arch_requirement(arch: str | None) -> str:
    return {"x64": "64-bit", "x86": "32-bit and 64-bit", "arm64": "ARM64"}.get(
        (arch or "").lower(), "32-bit and 64-bit")


def detection_script(*, app_name: str, version: str, display_name_regex: str | None,
                     product_code: str | None = None, key_pattern: str | None = None,
                     exclude: str | None = None, appx_name: str | None = None) -> str:
    """Intune custom detection script: writes output + exit 0 when installed."""
    rx = (display_name_regex or "^$").replace("'", "''")
    ex = (exclude or "").replace("'", "''")
    ax = (appx_name or "").replace("'", "''")
    pc = (product_code or "").replace("'", "''")
    kp = (key_pattern or "").replace("'", "''")
    return f"""<#
    AppDepot detection script
    Application : {app_name}
    Version     : {version} (or newer)
    Intune treats the app as installed when this script writes to STDOUT and exits 0.
#>
$ErrorActionPreference = 'SilentlyContinue'
$RequiredVersion = '{version}'
$DisplayNamePattern = '{rx}'
$ProductCode = '{pc}'
$KeyPattern = '{kp}'
$Exclude = '{ex}'
$AppxName = '{ax}'

function Get-VersionParts([string]$Version) {{
    @(($Version -replace '^[vV]', '') -split '[^0-9]+' | Where-Object {{ $_ -ne '' }} | ForEach-Object {{ [long]$_ }})
}}

function Compare-AppVersion([string]$A, [string]$B) {{
    $x = Get-VersionParts $A; $y = Get-VersionParts $B
    for ($i = 0; $i -lt [Math]::Max($x.Count, $y.Count); $i++) {{
        $p = if ($i -lt $x.Count) {{ $x[$i] }} else {{ 0 }}
        $q = if ($i -lt $y.Count) {{ $y[$i] }} else {{ 0 }}
        if ($p -gt $q) {{ return 1 }}
        if ($p -lt $q) {{ return -1 }}
    }}
    return 0
}}

$roots = @(
    'HKLM:\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall',
    'HKLM:\\SOFTWARE\\WOW6432Node\\Microsoft\\Windows\\CurrentVersion\\Uninstall'
)

if ($AppxName) {{
    # MSIX/AppX app (e.g. Teams): provisioned for all users, or installed for any user
    $pkgs = @(Get-AppxProvisionedPackage -Online | Where-Object {{ $_.DisplayName -eq $AppxName }} | ForEach-Object {{ [string]$_.Version }})
    $pkgs += @(Get-AppxPackage -AllUsers -Name $AppxName | ForEach-Object {{ [string]$_.Version }})
    foreach ($v in $pkgs) {{
        if ((Compare-AppVersion $v $RequiredVersion) -ge 0) {{ Write-Output "Detected $AppxName $v"; exit 0 }}
    }}
    exit 1
}}

if ($ProductCode) {{
    foreach ($root in $roots) {{
        if (Test-Path (Join-Path $root $ProductCode)) {{
            Write-Output "Detected $ProductCode"
            exit 0
        }}
    }}
}}

$entries = foreach ($root in $roots) {{ Get-ChildItem $root | Get-ItemProperty }}
foreach ($entry in $entries) {{
    if ($KeyPattern -and $entry.PSChildName -notmatch $KeyPattern) {{ continue }}
    if ($Exclude -and $entry.DisplayName -match $Exclude) {{ continue }}
    if ($entry.DisplayName -match $DisplayNamePattern -and $entry.DisplayVersion) {{
        if ((Compare-AppVersion $entry.DisplayVersion $RequiredVersion) -ge 0) {{
            Write-Output "Detected $($entry.DisplayName) $($entry.DisplayVersion)"
            exit 0
        }}
    }}
}}
exit 1
"""
